"""
Builds every generated asset:
  assets/sprites/<pet>.png   sprite sheet (bodies, eggs, overlays)
  src/assets/atlas.ts         cell lookup for the sheets
  assets/scenes/*.png         habitat layers
  assets/brand/*.png          logo, icons, splash
Run: python3 tools/art/build.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from PIL import Image

from pets import DRAWERS, MOODS, draw_egg, draw_overlay
from pixel import Canvas

ROOT = Path(__file__).resolve().parents[2]
SPRITES = ROOT / "assets" / "sprites"
ATLAS_TS = ROOT / "src" / "assets" / "atlas.ts"

from pets import PETS
STAGES = ["egg", "baby", "teen", "adult", "companion"]
EGG_FRAMES = ["idle", "wobble_l", "wobble_r", "crack1", "crack2", "crack3"]
MOTIONS = [0, 1, 2]
EYES = ["open", "blink", "happy"]
OVERLAYS = ["hydration", "active", "nourished", "cap", "bow", "glasses", "scarf", "crown"]
CELL = 128
COLS = 9


def build_sheet(pet: str):
    cells: list[tuple[str, Image.Image]] = []
    for f in EGG_FRAMES:
        c = Canvas()
        draw_egg(c, pet, f)
        cells.append((f"egg:{f}", c.image()))
    for stage in range(1, 5):
        for m in MOTIONS:
            for e in EYES:
                c = Canvas()
                DRAWERS[pet](c, stage, m, e)
                cells.append((f"{STAGES[stage]}:{m}:{e}", c.image()))
    for stage in range(1, 5):
        for mood in MOODS:
            c = Canvas()
            DRAWERS[pet](c, stage, 0, "open", mood)
            cells.append((f"mood:{STAGES[stage]}:{mood}", c.image()))
    for stage in range(1, 5):
        for kind in OVERLAYS:
            c = Canvas()
            draw_overlay(c, pet, stage, kind)
            cells.append((f"ov:{STAGES[stage]}:{kind}", c.image()))
    rows = (len(cells) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    index: dict[str, list[int]] = {}
    for i, (key, img) in enumerate(cells):
        x, y = (i % COLS) * CELL, (i // COLS) * CELL
        sheet.alpha_composite(img, (x, y))
        index[key] = [x, y]
    SPRITES.mkdir(parents=True, exist_ok=True)
    sheet.save(SPRITES / f"{pet}.png", optimize=True)
    for old in SPRITES.glob("*.png"):
        if old.stem not in PETS:
            old.unlink()
    return index, sheet.size


def main():
    atlas = {}
    sizes = {}
    for pet in PETS:
        atlas[pet], sizes[pet] = build_sheet(pet)
        print(f"{pet}: {len(atlas[pet])} cells, sheet {sizes[pet]}")
    ATLAS_TS.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/art/build.py. Do not edit by hand.",
        "export const CELL = 128;",
        "export type SheetKey = string;",
        "export const SHEET_SIZES = " + json.dumps(sizes) + " as const;",
        "export const ATLAS: Record<'tofu' | 'juno' | 'pebble' | 'ori' | 'fern', Record<string, [number, number]>> = "
        + json.dumps(atlas, separators=(",", ":"))
        + ";",
        "",
    ]
    ATLAS_TS.write_text("\n".join(lines))
    import scenes
    scenes.build(ROOT / "assets" / "scenes")
    import brand
    brand.build(ROOT / "assets")


if __name__ == "__main__":
    main()
